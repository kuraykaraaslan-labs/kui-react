import { describe, it, expect, vi } from 'vitest';
import { useState } from 'react';
import { render, screen, fireEvent, within } from '@testing-library/react';
import { AiHumanDraftEditor } from './index';

const HUMAN = 'The cache was cold after the deploy. We restarted the pod.';
const AI = 'The cache was warm after the deploy. We restarted the failing pod.';

function Harness({ initial = HUMAN, ai = AI, ...rest }: Partial<React.ComponentProps<typeof AiHumanDraftEditor>> & { initial?: string; ai?: string }) {
  const [value, setValue] = useState(initial);
  return (
    <>
      <AiHumanDraftEditor aiDraft={ai} value={value} onChange={setValue} {...rest} />
      <pre data-testid="value">{value}</pre>
    </>
  );
}
const value = () => screen.getByTestId('value').textContent;

describe('AiHumanDraftEditor', () => {
  it('shows both texts, an AI-generated badge and the model', () => {
    const { container } = render(<Harness model="claude-x" />);
    expect(screen.getByRole('heading', { name: 'AI draft' })).toBeInTheDocument();
    expect(screen.getByRole('heading', { name: 'Your text' })).toBeInTheDocument();
    expect(container.querySelector('[data-part="ai-badge"]')).toHaveTextContent('AI-generated by claude-x');
  });

  it('badges as AI-generated without a model name', () => {
    const { container } = render(<Harness />);
    expect(container.querySelector('[data-part="ai-badge"]')).toHaveTextContent('AI-generated');
  });

  it('counts pending changes and numbers hunks in both panels', () => {
    const { container } = render(<Harness />);
    expect(screen.getByText('2 changes pending')).toBeInTheDocument();
    expect(container.querySelectorAll('[data-hunk]')).toHaveLength(4); // two hunks, drawn in each panel
    expect(screen.getByRole('group', { name: 'Change 1 of 2' })).toBeInTheDocument();
    expect(screen.getByRole('group', { name: 'Change 2 of 2' })).toBeInTheDocument();
  });

  it('accepts one hunk: only that change enters the text', () => {
    const onAcceptHunk = vi.fn();
    render(<Harness onAcceptHunk={onAcceptHunk} />);
    fireEvent.click(screen.getByRole('button', { name: /Accept change 1:/ }));
    expect(value()).toBe('The cache was warm after the deploy. We restarted the pod.');
    expect(onAcceptHunk).toHaveBeenCalledWith(expect.objectContaining({ human: 'cold', ai: 'warm' }));
    expect(screen.getByText('1 changes pending')).toBeInTheDocument();
    expect(screen.getByRole('status')).toHaveTextContent('Accepted change 1.');
  });

  it('rejects a hunk: the text stays, the hunk stops being pending and can be reconsidered', () => {
    const onRejectedChange = vi.fn();
    render(<Harness onRejectedChange={onRejectedChange} />);
    fireEvent.click(screen.getByRole('button', { name: /Reject change 1:/ }));
    expect(value()).toBe(HUMAN);
    expect(onRejectedChange).toHaveBeenCalledTimes(1);
    expect(screen.getByText('1 changes pending')).toBeInTheDocument();
    expect(screen.getByText('(rejected)')).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: /Reconsider rejected change 1:/ }));
    expect(screen.getByText('2 changes pending')).toBeInTheDocument();
  });

  it('accepts all pending changes, but not rejected ones', () => {
    const onAcceptAll = vi.fn();
    render(<Harness onAcceptAll={onAcceptAll} />);
    fireEvent.click(screen.getByRole('button', { name: /Reject change 2:/ }));
    fireEvent.click(screen.getByRole('button', { name: 'Accept all' }));
    expect(value()).toBe('The cache was warm after the deploy. We restarted the pod.');
    expect(onAcceptAll).toHaveBeenCalledTimes(1);
  });

  it('accept all with nothing rejected gives the AI text', () => {
    render(<Harness />);
    fireEvent.click(screen.getByRole('button', { name: 'Accept all' }));
    expect(value()).toBe(AI);
    expect(screen.getByText('Your text matches the AI draft.')).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Accept all' })).toBeNull();
  });

  it('keep mine rejects every hunk and leaves the text alone', () => {
    render(<Harness />);
    fireEvent.click(screen.getByRole('button', { name: 'Keep mine' }));
    expect(value()).toBe(HUMAN);
    expect(screen.getByText('No changes pending')).toBeInTheDocument();
  });

  it('describes each action for screen readers: replace, insert and remove', () => {
    render(<Harness />);
    expect(screen.getByRole('button', { name: 'Accept change 1: replace “cold” with “warm”' })).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Accept change 2: insert “failing”' })).toBeInTheDocument();
  });

  it('marks changes by shape as well as colour: struck human text, underlined AI text', () => {
    const { container } = render(<Harness />);
    expect(container.querySelector('span.line-through')).toHaveTextContent('cold');
    expect(container.querySelector('span.underline')).toHaveTextContent('warm');
  });

  it('lets the person edit freely; the diff follows', () => {
    render(<Harness />);
    fireEvent.click(screen.getByRole('button', { name: 'Edit text' }));
    const area = screen.getByRole('textbox', { name: 'Your text' });
    fireEvent.change(area, { target: { value: AI } });
    expect(value()).toBe(AI);
    fireEvent.click(screen.getByRole('button', { name: 'Review changes' }));
    expect(screen.getByText('Your text matches the AI draft.')).toBeInTheDocument();
  });

  it('is read-only on request: no accept, reject or edit controls', () => {
    render(<Harness readOnly />);
    expect(screen.queryByRole('button')).toBeNull();
    expect(screen.getByText('2 changes pending')).toBeInTheDocument();
  });

  it('honours controlled rejected keys', () => {
    const { container, rerender } = render(<AiHumanDraftEditor aiDraft={AI} value={HUMAN} onChange={() => {}} rejected={[]} />);
    const key = container.querySelector('[data-hunk]')!.getAttribute('data-hunk')!;
    rerender(<AiHumanDraftEditor aiDraft={AI} value={HUMAN} onChange={() => {}} rejected={[key]} />);
    expect(screen.getByText('1 changes pending')).toBeInTheDocument();
    expect(within(screen.getAllByRole('group')[0]).getByRole('button', { name: /Reconsider/ })).toBeInTheDocument();
  });

  it('takes its text from messages', () => {
    render(<Harness messages={{ acceptAll: 'Tout accepter', aiPanel: 'Brouillon IA' }} />);
    expect(screen.getByRole('button', { name: 'Tout accepter' })).toBeInTheDocument();
    expect(screen.getByRole('heading', { name: 'Brouillon IA' })).toBeInTheDocument();
  });
});
