'use client';
// modules/ui/AiHumanDraftEditor/index.tsx
//
// AiHumanDraftEditor — the AI's draft beside the human's text, diffed by words, with accept / reject per hunk and
// accept all. The text stays the human's until they accept: the `value` is controlled and only changes through
// `onChange` when a hunk is accepted or the person edits. A badge says the draft is AI-generated. Differences are
// marked by shape (strike, underline, a number) as well as colour, and a hunk shows the same number in both panels.

import { useId, useMemo, useState } from 'react';
import { FontAwesomeIcon } from '@fortawesome/react-fontawesome';
import { faCheck, faPenToSquare, faRotateLeft, faWandMagicSparkles, faXmark } from '@fortawesome/free-solid-svg-icons';
import { cn } from '@/libs/utils/cn';
import { fillMessage } from '../_shared/format';
import { applySegments, buildSegments, hunksOf, type Hunk } from './diff';

export type { Hunk, Segment } from './diff';
export { buildSegments, applySegments, hunksOf, tokenize } from './diff';

export type AiHumanDraftEditorMessages = {
  aiBadge: string;
  /** `{model}` */
  aiBadgeModel: string;
  aiPanel: string;
  humanPanel: string;
  edit: string;
  review: string;
  editorLabel: string;
  accept: string;
  reject: string;
  acceptAll: string;
  keepMine: string;
  reconsider: string;
  /** `{count}` */
  pending: string;
  noPending: string;
  identical: string;
  /** `{index}`, `{total}` */
  changeLabel: string;
  /** `{index}`, `{summary}` */
  acceptAria: string;
  /** `{index}`, `{summary}` */
  rejectAria: string;
  /** `{index}`, `{summary}` */
  reconsiderAria: string;
  /** `{human}`, `{ai}` */
  replace: string;
  /** `{ai}` */
  insert: string;
  /** `{human}` */
  remove: string;
  nothing: string;
  removed: string;
  rejected: string;
  /** `{index}` */
  acceptedAnnounce: string;
  /** `{index}` */
  rejectedAnnounce: string;
  allAcceptedAnnounce: string;
  allRejectedAnnounce: string;
};

export const DEFAULT_AI_HUMAN_DRAFT_EDITOR_MESSAGES: AiHumanDraftEditorMessages = {
  aiBadge: 'AI-generated',
  aiBadgeModel: 'AI-generated by {model}',
  aiPanel: 'AI draft',
  humanPanel: 'Your text',
  edit: 'Edit text',
  review: 'Review changes',
  editorLabel: 'Your text',
  accept: 'Accept',
  reject: 'Reject',
  acceptAll: 'Accept all',
  keepMine: 'Keep mine',
  reconsider: 'Reconsider',
  pending: '{count} changes pending',
  noPending: 'No changes pending',
  identical: 'Your text matches the AI draft.',
  changeLabel: 'Change {index} of {total}',
  acceptAria: 'Accept change {index}: {summary}',
  rejectAria: 'Reject change {index}: {summary}',
  reconsiderAria: 'Reconsider rejected change {index}: {summary}',
  replace: 'replace “{human}” with “{ai}”',
  insert: 'insert “{ai}”',
  remove: 'remove “{human}”',
  nothing: '(nothing)',
  removed: '(removed)',
  rejected: 'rejected',
  acceptedAnnounce: 'Accepted change {index}.',
  rejectedAnnounce: 'Rejected change {index}.',
  allAcceptedAnnounce: 'All pending changes accepted.',
  allRejectedAnnounce: 'All pending changes rejected. Your text is unchanged.',
};

export type AiHumanDraftEditorProps = {
  /** The AI's draft. Read-only. */
  aiDraft: string;
  /** The human's text (controlled). */
  value: string;
  onChange: (value: string) => void;
  /** Keys of the hunks the person rejected (controlled). Rejected hunks stop counting as pending. */
  rejected?: string[];
  defaultRejected?: string[];
  onRejectedChange?: (keys: string[]) => void;
  /** Named in the AI badge. */
  model?: string;
  readOnly?: boolean;
  /** Minimum height of each panel in px. Default = 160. */
  minHeight?: number;
  onAcceptHunk?: (hunk: Hunk) => void;
  onRejectHunk?: (hunk: Hunk) => void;
  onAcceptAll?: () => void;
  messages?: Partial<AiHumanDraftEditorMessages>;
  className?: string;
};

export function AiHumanDraftEditor({
  aiDraft,
  value,
  onChange,
  rejected,
  defaultRejected,
  onRejectedChange,
  model,
  readOnly = false,
  minHeight = 160,
  onAcceptHunk,
  onRejectHunk,
  onAcceptAll,
  messages,
  className,
}: AiHumanDraftEditorProps) {
  const msg = useMemo(() => ({ ...DEFAULT_AI_HUMAN_DRAFT_EDITOR_MESSAGES, ...messages }), [messages]);
  const uid = useId();
  const [editing, setEditing] = useState(false);
  const [localRejected, setLocalRejected] = useState<string[]>(defaultRejected ?? []);
  const rejectedKeys = rejected ?? localRejected;
  const rejectedSet = useMemo(() => new Set(rejectedKeys), [rejectedKeys]);
  const [activeKey, setActiveKey] = useState<string | null>(null);
  const [announce, setAnnounce] = useState('');

  const setRejected = (next: string[]) => {
    if (rejected === undefined) setLocalRejected(next);
    onRejectedChange?.(next);
  };

  const segments = useMemo(() => buildSegments(value, aiDraft), [value, aiDraft]);
  const hunks = useMemo(() => hunksOf(segments), [segments]);
  const indexOf = useMemo(() => new Map(hunks.map((h, i) => [h.key, i + 1])), [hunks]);
  const pending = hunks.filter((h) => !rejectedSet.has(h.key));

  const summary = (h: Hunk) =>
    h.human && h.ai ? fillMessage(msg.replace, { human: h.human.trim(), ai: h.ai.trim() })
      : h.ai ? fillMessage(msg.insert, { ai: h.ai.trim() })
        : fillMessage(msg.remove, { human: h.human.trim() });

  const accept = (h: Hunk) => {
    const next = applySegments(segments, (x) => (x.key === h.key ? 'ai' : 'human'));
    onAcceptHunk?.(h);
    setAnnounce(fillMessage(msg.acceptedAnnounce, { index: indexOf.get(h.key) ?? 0 }));
    onChange(next);
  };
  const reject = (h: Hunk) => {
    onRejectHunk?.(h);
    setAnnounce(fillMessage(msg.rejectedAnnounce, { index: indexOf.get(h.key) ?? 0 }));
    setRejected([...rejectedKeys, h.key]);
  };
  const reconsider = (h: Hunk) => setRejected(rejectedKeys.filter((k) => k !== h.key));
  const acceptAll = () => {
    onAcceptAll?.();
    setAnnounce(msg.allAcceptedAnnounce);
    onChange(applySegments(segments, (x) => (rejectedSet.has(x.key) ? 'human' : 'ai')));
  };
  const keepMine = () => {
    setAnnounce(msg.allRejectedAnnounce);
    setRejected([...new Set([...rejectedKeys, ...hunks.map((h) => h.key)])]);
  };

  const badgeText = model ? fillMessage(msg.aiBadgeModel, { model }) : msg.aiBadge;
  const hl = (key: string) => activeKey === key;

  return (
    <div className={cn('flex flex-col gap-3', className)}>
      <div className="grid gap-3 md:grid-cols-2">
        {/* AI panel */}
        <section aria-labelledby={`${uid}-ai`} className="flex min-w-0 flex-col rounded-md border border-border bg-surface-raised">
          <header className="flex flex-wrap items-center justify-between gap-2 border-b border-border px-3 py-2">
            <h3 id={`${uid}-ai`} className="text-sm font-semibold text-text-primary">{msg.aiPanel}</h3>
            <span data-part="ai-badge" className="inline-flex items-center gap-1.5 rounded-full border border-secondary bg-surface-base px-2 py-0.5 text-xs font-medium text-secondary">
              <FontAwesomeIcon icon={faWandMagicSparkles} aria-hidden="true" className="h-3 w-3" />
              {badgeText}
            </span>
          </header>
          <div className="whitespace-pre-wrap break-words p-3 text-sm leading-6 text-text-primary" style={{ minHeight }}>
            {segments.map((s, i) => s.type === 'equal'
              ? <span key={i}>{s.text}</span>
              : <AiHunk key={s.hunk.key} hunk={s.hunk} index={indexOf.get(s.hunk.key) ?? 0} rejected={rejectedSet.has(s.hunk.key)} active={hl(s.hunk.key)} msg={msg} onActive={setActiveKey} />)}
          </div>
        </section>

        {/* Human panel */}
        <section aria-labelledby={`${uid}-human`} className="flex min-w-0 flex-col rounded-md border border-border bg-surface-raised">
          <header className="flex flex-wrap items-center justify-between gap-2 border-b border-border px-3 py-2">
            <h3 id={`${uid}-human`} className="text-sm font-semibold text-text-primary">{msg.humanPanel}</h3>
            {!readOnly && (
              <button
                type="button"
                aria-pressed={editing}
                onClick={() => setEditing((v) => !v)}
                className={cn(ghost, editing && 'border-primary bg-primary-subtle text-primary')}
              >
                <FontAwesomeIcon icon={faPenToSquare} aria-hidden="true" className="me-1.5 h-3 w-3" />
                {editing ? msg.review : msg.edit}
              </button>
            )}
          </header>
          {editing && !readOnly ? (
            <textarea
              aria-label={msg.editorLabel}
              value={value}
              onChange={(e) => onChange(e.target.value)}
              className="w-full flex-1 resize-y rounded-b-md bg-surface-base p-3 text-sm leading-6 text-text-primary focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-border-focus"
              style={{ minHeight }}
            />
          ) : (
            <div className="whitespace-pre-wrap break-words p-3 text-sm leading-6 text-text-primary" style={{ minHeight }}>
              {segments.map((s, i) => s.type === 'equal'
                ? <span key={i}>{s.text}</span>
                : (
                  <HumanHunk
                    key={s.hunk.key}
                    hunk={s.hunk}
                    index={indexOf.get(s.hunk.key) ?? 0}
                    total={hunks.length}
                    rejected={rejectedSet.has(s.hunk.key)}
                    active={hl(s.hunk.key)}
                    readOnly={readOnly}
                    msg={msg}
                    summary={summary(s.hunk)}
                    onActive={setActiveKey}
                    onAccept={() => accept(s.hunk)}
                    onReject={() => reject(s.hunk)}
                    onReconsider={() => reconsider(s.hunk)}
                  />
                ))}
            </div>
          )}
        </section>
      </div>

      <div className="flex flex-wrap items-center gap-2">
        <p className="text-sm text-text-secondary" data-part="pending">
          {hunks.length === 0 ? msg.identical : pending.length === 0 ? msg.noPending : fillMessage(msg.pending, { count: pending.length })}
        </p>
        {!readOnly && pending.length > 0 && (
          <div className="ms-auto flex gap-2">
            <button type="button" className={ghost} onClick={keepMine}>
              <FontAwesomeIcon icon={faXmark} aria-hidden="true" className="me-1.5 h-3 w-3" />{msg.keepMine}
            </button>
            <button type="button" className={cn(ghost, 'border-primary bg-primary text-primary-fg hover:bg-primary-hover')} onClick={acceptAll}>
              <FontAwesomeIcon icon={faCheck} aria-hidden="true" className="me-1.5 h-3 w-3" />{msg.acceptAll}
            </button>
          </div>
        )}
      </div>
      <div className="sr-only" role="status" aria-live="polite">{announce}</div>
    </div>
  );
}

const ghost = cn(
  'inline-flex items-center rounded border border-border bg-surface-base px-2 py-1 text-xs font-medium text-text-primary transition-colors',
  'hover:bg-surface-overlay disabled:cursor-not-allowed disabled:opacity-50 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-border-focus',
);

function Num({ n }: { n: number }) {
  return <sup aria-hidden="true" className="mx-0.5 rounded bg-surface-sunken px-1 text-[10px] font-semibold text-text-secondary">{n}</sup>;
}

function AiHunk({ hunk, index, rejected, active, msg, onActive }: {
  hunk: Hunk; index: number; rejected: boolean; active: boolean; msg: AiHumanDraftEditorMessages; onActive: (key: string | null) => void;
}) {
  return (
    <span
      data-hunk={hunk.key}
      data-rejected={rejected || undefined}
      onMouseEnter={() => onActive(hunk.key)}
      onMouseLeave={() => onActive(null)}
      className={cn(
        'rounded-sm underline decoration-2 underline-offset-2',
        rejected ? 'text-text-disabled decoration-border' : 'bg-secondary/10 decoration-secondary',
        active && 'bg-secondary/25',
      )}
    >
      <Num n={index} />
      {hunk.ai || <em className="not-italic text-text-secondary">{msg.removed}</em>}
    </span>
  );
}

function HumanHunk({ hunk, index, total, rejected, active, readOnly, msg, summary, onActive, onAccept, onReject, onReconsider }: {
  hunk: Hunk; index: number; total: number; rejected: boolean; active: boolean; readOnly: boolean; msg: AiHumanDraftEditorMessages;
  summary: string; onActive: (key: string | null) => void; onAccept: () => void; onReject: () => void; onReconsider: () => void;
}) {
  return (
    <span
      role="group"
      aria-label={fillMessage(msg.changeLabel, { index, total })}
      data-hunk={hunk.key}
      data-rejected={rejected || undefined}
      onMouseEnter={() => onActive(hunk.key)}
      onMouseLeave={() => onActive(null)}
      onFocus={() => onActive(hunk.key)}
      onBlur={() => onActive(null)}
      className={cn('rounded-sm', rejected ? 'opacity-60' : 'bg-error-subtle/60', active && 'bg-error-subtle')}
    >
      <Num n={index} />
      <span className={cn(!rejected && hunk.ai && 'line-through decoration-error decoration-2')}>
        {hunk.human || <em className="not-italic text-text-secondary">{msg.nothing}</em>}
      </span>
      {rejected && <span className="ms-1 text-xs text-text-secondary">({msg.rejected})</span>}
      {!readOnly && (
        <span className="ms-1 inline-flex gap-1 align-baseline">
          {rejected ? (
            <button type="button" aria-label={fillMessage(msg.reconsiderAria, { index, summary })} className={chip} onClick={onReconsider}>
              <FontAwesomeIcon icon={faRotateLeft} aria-hidden="true" className="h-2.5 w-2.5" />{msg.reconsider}
            </button>
          ) : (
            <>
              <button type="button" aria-label={fillMessage(msg.acceptAria, { index, summary })} className={cn(chip, 'border-success text-success-fg')} onClick={onAccept}>
                <FontAwesomeIcon icon={faCheck} aria-hidden="true" className="h-2.5 w-2.5" />{msg.accept}
              </button>
              <button type="button" aria-label={fillMessage(msg.rejectAria, { index, summary })} className={cn(chip, 'border-error text-error-fg')} onClick={onReject}>
                <FontAwesomeIcon icon={faXmark} aria-hidden="true" className="h-2.5 w-2.5" />{msg.reject}
              </button>
            </>
          )}
        </span>
      )}
    </span>
  );
}

const chip = cn(
  'inline-flex items-center gap-1 rounded border bg-surface-base px-1.5 text-[11px] font-medium leading-5 transition-colors hover:bg-surface-overlay',
  'focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-border-focus',
);
