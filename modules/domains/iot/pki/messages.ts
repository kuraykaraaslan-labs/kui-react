type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };
export type PkiMessages = Widen<typeof PKI_MESSAGES>;
export type PkiMessagesInput = { [K in keyof PkiMessages]?: Partial<PkiMessages[K]> };

export function mergePkiMessages(input?: PkiMessagesInput): PkiMessages {
  const out = { ...PKI_MESSAGES } as PkiMessages;
  for (const k of Object.keys(input ?? {}) as Array<keyof PkiMessages>) out[k] = { ...PKI_MESSAGES[k], ...(input?.[k] ?? {}) } as never;
  return out;
}

export const fillText = (t: string, v: Record<string, string | number>): string => t.replace(/\{(\w+)\}/g, (_, k: string) => (k in v ? String(v[k]) : `{${k}}`));
