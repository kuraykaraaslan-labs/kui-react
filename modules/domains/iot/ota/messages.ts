export type OtaMessages = typeof OTA_MESSAGES;
type Deep<T> = { [K in keyof T]?: T[K] extends string ? string : Deep<T[K]> };
export type OtaMessagesInput = Deep<OtaMessages>;

const isObj = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);

function merge<T>(base: T, over: unknown): T {
  if (!isObj(over)) return base;
  const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
  for (const [k, v] of Object.entries(over)) {
    if (v === undefined) continue;
    out[k] = isObj(v) && isObj(out[k]) ? merge(out[k], v) : v;
  }
  return out as T;
}

export function mergeOtaMessages(...inputs: Array<OtaMessagesInput | undefined>): OtaMessages {
  return inputs.reduce<OtaMessages>((acc, i) => merge(acc, i), OTA_MESSAGES);
}

/** Every text as `group.key` with its English: a host's dictionary walk. */
export function flattenOtaMessages(m: OtaMessages = OTA_MESSAGES): Record<string, string> {
  const out: Record<string, string> = {};
  const go = (v: unknown, prefix: string) => {
    if (typeof v === 'string') { out[prefix] = v; return; }
    if (isObj(v)) for (const [k, x] of Object.entries(v)) go(x, prefix ? `${prefix}.${k}` : k);
  };
  go(m, '');
  return out;
}

/** The whole set from a host's dictionary: `otaMessagesFrom((key, en) => t(\`iot_ota.kit.${key}\`, en))`. */
export function otaMessagesFrom(translate: (key: string, english: string) => string): OtaMessages {
  const go = (v: unknown, prefix: string): unknown => {
    if (typeof v === 'string') return translate(prefix, v);
    if (!isObj(v)) return v;
    const out: Record<string, unknown> = {};
    for (const [k, x] of Object.entries(v)) out[k] = go(x, prefix ? `${prefix}.${k}` : k);
    return out;
  };
  return go(OTA_MESSAGES, '') as OtaMessages;
}
