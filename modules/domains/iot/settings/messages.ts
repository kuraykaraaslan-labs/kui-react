export type SettingsMessages = typeof SETTINGS_MESSAGES;
type Deep<T> = { [K in keyof T]?: T[K] extends string ? string : T[K] extends Record<string, string> ? Record<string, string> : Deep<T[K]> };
export type SettingsMessagesInput = Deep<SettingsMessages>;

const isObj = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);

function merge<T>(base: T, over: unknown): T {
  if (!isObj(over)) return base;
  const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
  for (const [k, v] of Object.entries(over)) {
    if (v === undefined) continue;
    out[k] = isObj(v) && isObj(out[k]) ? merge(out[k], v) : v;
  }
  return out as T;
}

export function mergeSettingsMessages(...inputs: Array<SettingsMessagesInput | undefined>): SettingsMessages {
  return inputs.reduce<SettingsMessages>((acc, i) => merge(acc, i), SETTINGS_MESSAGES);
}

/** Every text as `group.key` (nested groups joined by dots) with its English: a host's dictionary walk. */
export function flattenSettingsMessages(m: SettingsMessages = SETTINGS_MESSAGES): Record<string, string> {
  const out: Record<string, string> = {};
  const go = (v: unknown, prefix: string) => {
    if (typeof v === 'string') { out[prefix] = v; return; }
    if (isObj(v)) for (const [k, x] of Object.entries(v)) go(x, prefix ? `${prefix}.${k}` : k);
  };
  go(m, '');
  return out;
}

/**
 * Every text through a host's translate function, keyed `<prefix>.<group>.<key>` (a key of `fields` and `values` keeps its own dots):
 * `settingsMessagesFrom((key, en) => t(\`iot_device_settings.kit.${key}\`, en))`.
 */
export function settingsMessagesFrom(translate: (key: string, english: string) => string): SettingsMessages {
  const go = (v: unknown, prefix: string): unknown => {
    if (typeof v === 'string') return translate(prefix, v);
    if (!isObj(v)) return v;
    const out: Record<string, unknown> = {};
    for (const [k, x] of Object.entries(v)) out[k] = go(x, prefix ? `${prefix}.${k}` : k);
    return out;
  };
  return go(SETTINGS_MESSAGES, '') as SettingsMessages;
}
