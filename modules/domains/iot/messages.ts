type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };
export type IotMessages = Widen<typeof IOT_MESSAGES>;
export type IotMessagesInput = { [K in keyof IotMessages]?: Partial<IotMessages[K]> };

/** Defaults with a host's (partial) translations on top, group by group. */
export function mergeIotMessages(...layers: Array<IotMessagesInput | undefined>): IotMessages {
  const out: Record<string, Record<string, string>> = {};
  for (const [group, texts] of Object.entries(IOT_MESSAGES)) out[group] = { ...texts };
  for (const layer of layers) {
    if (!layer) continue;
    for (const [group, texts] of Object.entries(layer)) {
      if (texts && out[group]) Object.assign(out[group], texts);
    }
  }
  return out as unknown as IotMessages;
}
