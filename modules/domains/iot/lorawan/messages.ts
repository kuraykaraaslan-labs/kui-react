type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };
export type LoraMessages = Widen<typeof LORA_MESSAGES>;
export type LoraMessagesInput = { [K in keyof LoraMessages]?: Partial<LoraMessages[K]> };

export function mergeLoraMessages(input?: LoraMessagesInput): LoraMessages {
  const out = { ...LORA_MESSAGES } as LoraMessages;
  for (const k of Object.keys(input ?? {}) as Array<keyof LoraMessages>) out[k] = { ...LORA_MESSAGES[k], ...(input?.[k] ?? {}) } as never;
  return out;
}

export const fillText = (t: string, v: Record<string, string | number>): string => t.replace(/\{(\w+)\}/g, (_, k: string) => (k in v ? String(v[k]) : `{${k}}`));
